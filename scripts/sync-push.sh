#!/usr/bin/env bash
# Vendor the shared push module (push/src, canonical) into both services, which are deployed as
# self-contained directories (bridge/src/push).
# Run after every change in push/src; bridge/test/push-*.test.mjs
# fail when a vendored copy is out of date.
set -euo pipefail
cd "$(dirname "$0")/.."
for dst in bridge/src/push; do
  mkdir -p "$dst"
  rm -f "$dst"/*.mjs
  for f in push/src/*.mjs; do
    { echo "// GENERATED by scripts/sync-push.sh from push/src/$(basename "$f") - edit the canonical copy, then re-run."; cat "$f"; } > "$dst/$(basename "$f")"
  done
done
echo "push module synced into bridge/src/push"
