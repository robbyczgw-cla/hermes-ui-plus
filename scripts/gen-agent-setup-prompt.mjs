#!/usr/bin/env node
// Bundles the canonical "set up with your agent" prompt (docs/SETUP-WITH-AGENT.md, between the
// agent-setup-prompt markers) into the app as app/src/onboarding/agentSetupPrompt.generated.ts.
// Usage: node scripts/gen-agent-setup-prompt.mjs [--check]   (--check: exit 1 if the module is stale)
// app/src/onboarding/agentSetupPrompt.test.ts fails when the module and the doc differ.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOC = 'docs/SETUP-WITH-AGENT.md';
const OUT = 'app/src/onboarding/agentSetupPrompt.generated.ts';

/** the prompt between the markers (same rule as website/build.mjs) */
export function extractSetupPrompt(md) {
  const m = /<!-- agent-setup-prompt:begin -->\n```text\n([\s\S]*?)\n```\n<!-- agent-setup-prompt:end -->/.exec(md);
  if (!m) throw new Error(`${DOC}: agent-setup-prompt block not found`);
  return m[1];
}

export function renderModule(prompt) {
  return [
    `// GENERATED by scripts/gen-agent-setup-prompt.mjs from ${DOC} (agent-setup-prompt block). Do not edit:`,
    `// change the doc and run \`node scripts/gen-agent-setup-prompt.mjs\`. agentSetupPrompt.test.ts checks the sync.`,
    `/** The canonical setup prompt (English in every UI language). */`,
    `export const AGENT_SETUP_PROMPT = ${JSON.stringify(prompt)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = renderModule(extractSetupPrompt(readFileSync(join(ROOT, DOC), 'utf8')));
  let cur = '';
  try {
    cur = readFileSync(join(ROOT, OUT), 'utf8');
  } catch {
    // first run
  }
  if (process.argv.includes('--check')) {
    if (cur !== next) {
      console.error(`${OUT} is stale: run node scripts/gen-agent-setup-prompt.mjs`);
      process.exit(1);
    }
  } else if (cur !== next) {
    writeFileSync(join(ROOT, OUT), next);
    console.log(`wrote ${OUT}`);
  }
}
