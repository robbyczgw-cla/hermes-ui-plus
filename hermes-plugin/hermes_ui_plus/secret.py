"""Shared secret between the UI Bridge and this plugin's loopback listener.

Stored as one line in ``HERMES_HOME/hermes-ui-plus/secret`` (directory 0700, file 0600) unless
``server.secret_file`` points elsewhere. Generated by the installer (install.py), never logged, compared in constant time.
"""

from __future__ import annotations

import hashlib
import hmac
import os
import secrets
from pathlib import Path

SECRET_BYTES = 32
MIN_SECRET_LEN = 32


def default_secret_path(hermes_home: Path) -> Path:
    return Path(hermes_home) / "hermes-ui-plus" / "secret"


def create_secret(path: Path, *, group_readable: bool = False) -> bool:
    """Installer side: write a fresh random secret (0600, or 0640 with *group_readable*) if *path* does not
    exist yet. Returns True when a new secret was written. Never overwrites an existing file."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        return False
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(secrets.token_urlsafe(SECRET_BYTES) + "\n")
    if group_readable:  # bridge runs as another user in the file's group
        os.chmod(path, 0o640)
        os.chmod(path.parent, 0o750)
    return True


def load_secret(path: Path) -> str:
    """Plugin side: read the installer-generated secret. Raises FileNotFoundError when missing (the listener
    then stays off), PermissionError when group-writable/world-accessible, ValueError when too short."""
    path = Path(path)
    mode = path.stat().st_mode & 0o777
    if mode & 0o077 and not _group_read_allowed(path, mode):
        raise PermissionError(f"secret file {path} must be mode 600 (or 640)")
    token = path.read_text(encoding="utf-8").strip()
    if len(token) < MIN_SECRET_LEN:
        raise ValueError(f"secret in {path} is too short (min {MIN_SECRET_LEN} characters)")
    return token


def _group_read_allowed(path: Path, mode: int) -> bool:
    """Allow exactly 0640 (owner rw, group r) so a bridge running as another user in the file's group can
    read it; anything world-accessible or group-writable is refused."""
    return mode == 0o640


class SecretCheck:
    """Constant-time Bearer check against the shared secret (hash first: equal-length compare)."""

    def __init__(self, secret: str):
        self._digest = hashlib.sha256(secret.encode("utf-8")).digest()

    def check_header(self, authorization: str | None) -> bool:
        value = (authorization or "").strip()
        scheme, _, token = value.partition(" ")
        candidate = token.strip() if scheme.lower() == "bearer" else ""
        digest = hashlib.sha256(candidate.encode("utf-8")).digest()
        ok = hmac.compare_digest(digest, self._digest)
        return ok and bool(candidate)
