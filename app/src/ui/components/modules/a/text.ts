export type ModuleStrings = ReturnType<typeof makeS>;

const byT = new WeakMap<TFn, ModuleStrings>();

/** `makeS(t)` memoized per translate function (one per active language): 213 lookups once, not per component. */
export function stringsFor(t: TFn): ModuleStrings {
  let s = byT.get(t);
  if (!s) byT.set(t, (s = makeS(t)));
  return s;
}

/** German table: default for pure helpers / tests when no translated table is passed. */
export const S_DE: ModuleStrings = makeS(makeT('de', 'de-DE'));
