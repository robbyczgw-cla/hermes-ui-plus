/**
 * Conversation store types. Erasable TS only (tested with node --test).
 */
import type { ChatMessage } from '../hermes/types';
import type { HermesChatOptions } from '../hermes/capabilities';
import type { ModelLockState } from '../hermes/modelLock';

export type { ChatMessage, HermesChatOptions };

/** Backend of a conversation (same values as settings/profiles ProfileKind). */
export type ProfileKind = 'hermes' | 'demo';
export const PROFILE_KINDS: readonly ProfileKind[] = ['hermes', 'demo'];

/** Minimal profile shape needed to start a conversation (ConnectionProfile satisfies it). */
export type ProfileRef = { id: string; kind: ProfileKind };

export type ConversationMeta = {
  id: string;
  title: string;
  /**
   * `auto` = derived from first user message (may be replaced later), `user` = renamed by the user,
   * `meta` = generated by the bridge's auto-title (replaces `auto`; replaced by `remote`, never by the first message),
   * `remote` = title Hermes generated/stored for the session (replaces `auto`/`meta`, never `user`)
   */
  titleSource: 'auto' | 'user' | 'meta' | 'remote';
  profileId: string;
  profileKind: ProfileKind;
  /** X-Hermes-Session-Id of this chat (hermes) / local session id (claude) */
  hermesSessionId?: string;
  /**
   * Hermes profile ("bot") of this chat (hermes/bots.ts): its requests go to `/p/<bot>/…`; undefined = the default
   * profile. Fixed once the chat has messages (the session lives in that bot).
   */
  hermesProfile?: string;
  createdAt: number;
  updatedAt: number;
  pinned?: boolean;
  /** one-line preview of the latest message; '' = nothing sent yet (draft, hidden from the list) */
  preview: string;
  /** number of stored messages (after the size cap) */
  messageCount: number;
  /** model chosen for this chat (header model picker); undefined = profile default */
  model?: string;
  // ---- additions (Hermes session sync, per-chat options) ----
  /** Hermes reasoning/fast options for this chat (HermesOptionsSheet); undefined = server defaults */
  modelOptions?: HermesChatOptions;
  /** Hermes v0.22: outcome of locking `model` on the Hermes session (hermes/modelLock.ts); stale when `model` changed */
  modelLock?: ModelLockState;
  /** `remote` = created from the Hermes session list (started on Telegram/CLI/another device), not in this app */
  origin?: 'remote';
  /** last known server-side state of `hermesSessionId` (set by the session sync) */
  remote?: RemoteInfo;
  // ---- chat menu / answer menu ----
  /** "Archivieren": hidden from the main list, shown under "Archiv" (local only, the Hermes session is untouched) */
  archived?: boolean;
  /**
   * Hermes chat branched from an earlier answer: the first N messages are local copies its (fresh) session does
   * not know yet → they go along as a context block until a turn was accepted (hermes/turnOverride.ts)
   */
  branchSeed?: number;
  /**
   * the stored transcript was cut to MESSAGE_CAP / MESSAGES_MAX_BYTES at least once: older messages are no longer on
   * this device (the chat shows a marker at the top). Sticky.
   */
  historyTruncated?: boolean;
};

export type RemoteInfo = {
  /** Hermes session `source`: `api_server` (app/API), `telegram`, `cli`, … */
  source: string;
  /** server last activity (ms) */
  lastActive?: number;
  /** stored message rows on the server (incl. tool rows) */
  remoteCount?: number;
  /** title Hermes has for the session */
  title?: string;
  /** when the transcript was last loaded from Hermes (ms); undefined = never (only the list entry is known) */
  loadedAt?: number;
};

/** What goes into AsyncStorage as `index`. */
export type IndexState = {
  items: ConversationMeta[];
  /** conversation that was open last (restored on app start) */
  activeId?: string;
  /** Hermes session ids removed from the list by the user ("Nur aus Liste entfernen"); the sync skips them */
  hiddenRemote?: string[];
};

export type IndexFile = { v: number } & IndexState;
export type MessagesFile = { v: number; messages: ChatMessage[] };

export const SCHEMA_VERSION = 1;
export const DEFAULT_TITLE = 'Neuer Chat';
export const TITLE_MAX = 40;
export const PREVIEW_MAX = 90;
export const MESSAGE_CAP = 300;
/** AsyncStorage rows on Android are limited (~2 MB per row on the CursorWindow), stay well below. */
export const MESSAGES_MAX_BYTES = 1_500_000;

export type SearchHit = {
  meta: ConversationMeta;
  /** where it matched */
  in: 'title' | 'message';
  /** text excerpt around the first message match (only for `in: 'message'`) */
  snippet?: string;
};
